import assert from "node:assert/strict";
import { mkdtemp, readdir, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { fileURLToPath, pathToFileURL } from "node:url";
import { build } from "vite";
import solid from "vite-plugin-solid";
import { boot, sleep } from "../helpers/jsdom-app.mjs";
import { RESPONSES } from "../helpers/mount-guard.mjs";

const until = async (read) => { for (let i = 0; i < 80; i++) { if (read()) return true; await sleep(50); } return false; };
test("organization tooltip shares hover reads, refreshes on existing events and shows unavailable for a mismatched organization", async (t) => {
  const dir = await mkdtemp(join(tmpdir(), "danil-org-tooltip-")); t.after(() => rm(dir, { recursive: true, force: true }));
  await build({ configFile: false, root: fileURLToPath(new URL("../../", import.meta.url)), plugins: [solid()], logLevel: "silent", define: { __TERMINUS_VERSION__: JSON.stringify("test") }, build: { outDir: dir, emptyOutDir: true, lib: { entry: fileURLToPath(new URL("../helpers/organization-tooltip.tsx", import.meta.url)), formats: ["es"], fileName: () => "fixture.mjs" }, rollupOptions: { output: { inlineDynamicImports: true } } } });
  const app = await boot("listo", "org-tooltip-host", RESPONSES);
  const doc = app.w.document;
  const style = doc.createElement("style"); style.textContent = (await Promise.all((await readdir(dir)).filter((file) => file.endsWith(".css")).map((file) => readFile(join(dir, file), "utf8")))).join("\n"); doc.head.append(style);
  const root = doc.createElement("div"); doc.body.append(root);
  const { mountOrganizationTooltip, mountOrganizationStack, mountOrganizationMenu, mountOrganizationLayout, mountOrganizationGroup, mountWebOrganization } = await import(pathToFileURL(join(dir, "fixture.mjs")).href);
  const mounted = mountOrganizationTooltip(root); t.after(mounted.dispose);
  const trigger = doc.querySelector("#org-tooltip-tile");
  const hover = (inside) => trigger.dispatchEvent(new app.w.PointerEvent(inside ? "pointerenter" : "pointerleave", { bubbles: true, pointerType: "mouse" }));
  hover(true);
  assert.ok(await until(() => doc.querySelector("[data-organization-tooltip]")?.textContent.includes("Danil Credits")));
  assert.ok(doc.querySelector("[data-organization-tooltip]").textContent.includes("Organización · one@example.com"));
  assert.equal(mounted.reads(), 1);
  hover(false); await sleep(30); hover(true); await sleep(30);
  assert.equal(mounted.reads(), 1, "two hovers share the scoped read");
  mounted.unavailable(); app.w.dispatchEvent(new app.w.CustomEvent("danil:organization-changed"));
  assert.ok(await until(() => doc.querySelector("[data-organization-tooltip]")?.textContent.includes("No disponible")));
  assert.equal(mounted.reads(), 2);
  hover(false); trigger.focus();
  assert.ok(await until(() => doc.querySelector("[data-organization-tooltip]")));
  assert.equal(mounted.reads(), 2, "keyboard focus shares the same cache");
  mounted.dispose(); root.replaceChildren();
  const stack = mountOrganizationStack(root); t.after(stack.dispose);
  const button = doc.querySelector('[data-org-stack="org"]');
  button.focus();
  assert.ok(await until(() => doc.querySelector('[data-org-stack-panel="org"]')), JSON.stringify({ failures: app.failures, button: button.outerHTML, active: doc.activeElement?.outerHTML?.slice(0, 300) }));
  assert.equal(doc.activeElement, button, "Tab opens the column without moving focus");
  assert.match(app.w.getComputedStyle(doc.querySelector(".organization-stack-row")).animation, /(?:140ms|\.14s)/);
  assert.equal(button.getAttribute("aria-expanded"), "true");
  button.dispatchEvent(new app.w.KeyboardEvent("keydown", { key: "ArrowDown", bubbles: true }));
  assert.ok(await until(() => doc.activeElement?.getAttribute("data-workspace-tile") === "one"));
  doc.activeElement.dispatchEvent(new app.w.KeyboardEvent("keydown", { key: "ArrowDown", bubbles: true }));
  assert.equal(doc.activeElement.getAttribute("data-workspace-tile"), "two");
  doc.activeElement.dispatchEvent(new app.w.KeyboardEvent("keydown", { key: "ArrowDown", bubbles: true }));
  assert.equal(doc.activeElement.getAttribute("data-org-pin"), "org");
  doc.activeElement.dispatchEvent(new app.w.KeyboardEvent("keydown", { key: "Escape", bubbles: true }));
  assert.ok(await until(() => !doc.querySelector('[data-org-stack-panel="org"]')));
  assert.equal(doc.activeElement, button);
  button.dispatchEvent(new app.w.KeyboardEvent("keydown", { key: "Enter", bubbles: true }));
  assert.ok(await until(() => doc.activeElement?.getAttribute("data-workspace-tile") === "one"));
  doc.activeElement.click();
  assert.deepEqual(stack.opened, ["context/one"]);
  assert.ok(await until(() => !doc.querySelector('[data-org-stack-panel="org"]')));

  stack.dispose(); root.replaceChildren();
  app.w.matchMedia = () => ({ matches: true, addEventListener() {}, removeEventListener() {} });
  const reduced = mountOrganizationStack(root); t.after(reduced.dispose);
  const reducedTrigger = doc.querySelector('[data-org-stack="org"]');
  reducedTrigger.dispatchEvent(new app.w.PointerEvent("pointerenter", { bubbles: true }));
  await sleep(100); assert.equal(reducedTrigger.getAttribute("aria-expanded"), "false");
  assert.ok(await until(() => doc.querySelector('[data-org-stack-panel="org"]')));
  assert.equal(app.w.getComputedStyle(doc.querySelector(".organization-stack-row")).animation, "none");
  doc.querySelector('[data-org-pin="org"]').click();
  assert.equal(reduced.pinned(), 1);
  await sleep(0);
  reducedTrigger.dispatchEvent(new app.w.KeyboardEvent("keydown", { key: "ContextMenu", bubbles: true }));
  reducedTrigger.dispatchEvent(new app.w.KeyboardEvent("keydown", { key: "F10", shiftKey: true, bubbles: true }));
  assert.equal(reduced.menus(), 2);
  reducedTrigger.dispatchEvent(new app.w.KeyboardEvent("keydown", { key: "ArrowUp", altKey: true, bubbles: true }));
  assert.deepEqual(reduced.moves, [-1]);
  reducedTrigger.dispatchEvent(new app.w.KeyboardEvent("keydown", { key: " ", bubbles: true }));
  assert.ok(await until(() => doc.activeElement?.getAttribute("data-workspace-tile") === "one"));
  const outside = doc.createElement("button"); doc.body.append(outside); outside.focus();
  assert.ok(await until(() => !doc.querySelector('[data-org-stack-panel="org"]')));
  assert.equal(doc.activeElement, outside, "leaving with Tab closes without stealing focus");
  outside.remove();

  reduced.dispose(); root.replaceChildren();
  for (const role of ["admin", "member"]) {
    const menu = mountOrganizationMenu(root, role);
    const labels = [...root.querySelectorAll('[role="menuitem"]')].map((button) => button.textContent);
    assert.deepEqual(labels, ["Abrir", "Administrar workspaces", "Ocultar de la barra", ...(role === "admin" ? ["Canjear código"] : []), "Fijar en la barra", "Subir organización⌥↑", "Bajar organización⌥↓", "Cerrar sesión de Acme", "Cerrar sesión de one@example.com"]);
    assert.ok(!root.textContent.includes("Danil Credits"), "the balance belongs in the tooltip, not the menu");
    assert.equal(menu.reads(), 0);
    [...root.querySelectorAll("button")].find((button) => button.textContent === "Fijar en la barra").click();
    assert.deepEqual(menu.actions, ["pin"]);
    [...root.querySelectorAll("button")].find((button) => button.textContent === "Cerrar sesión de Acme").click();
    assert.ok(await until(() => menu.actions.includes("dismiss")));
    assert.deepEqual(menu.actions, ["pin", "close/context", "dismiss"]);
    menu.dispose(); root.replaceChildren();
  }

  const layout = mountOrganizationLayout(root); t.after(layout.dispose);
  const order = () => [...root.querySelectorAll("[data-rail-organization]")].map((element) => element.getAttribute("data-rail-organization"));
  assert.deepEqual(order(), ["b", "a"]);
  assert.equal(root.querySelectorAll('[data-rail-organization="a"]').length, 1, "two emails have one organization group");
  assert.deepEqual([...root.querySelectorAll('[data-rail-organization="a"] [data-layout-context]')].map((node) => node.getAttribute("data-layout-context")), ["one", "one", "two"]);
  layout.add(); assert.deepEqual(order(), ["b", "a", "c"]);
  layout.change("a", "up"); assert.deepEqual(order(), ["a", "b", "c"]);
  layout.change("a", "down"); assert.deepEqual(order(), ["b", "a", "c"]);
  layout.height(100);
  assert.ok(root.querySelector('[data-layout-stack="a"]'));
  assert.equal(root.querySelector('[data-layout-stack="b"]'), null, "pinned organizations never stack");
  assert.equal(root.querySelector('[data-layout-stack="c"]'), null, "a single tile never stacks");
  layout.active({ workspace: "a3", context: "two" });
  assert.equal(root.querySelector('[data-layout-stack="a"]'), null, "the opened organization never stacks");
  layout.active(null); layout.change("a", "pin");
  assert.equal(root.querySelector('[data-layout-stack="a"]'), null);
  assert.equal(root.querySelector('[data-rail-organization="a"]').getAttribute("aria-label"), "a, fijada");

  layout.dispose(); root.replaceChildren();
  const measured = mountOrganizationLayout(root, false); t.after(measured.dispose);
  assert.ok(await until(() => root.querySelector('[data-layout-stack="a"]')));
  measured.height(500);
  assert.ok(await until(() => !root.querySelector('[data-layout-stack="a"]')));
  measured.height(100);
  assert.ok(await until(() => root.querySelector('[data-layout-stack="a"]')));
  measured.dispose(); root.replaceChildren();
  const integrated = mountOrganizationGroup(root); t.after(integrated.dispose);
  const copies = [...root.querySelectorAll('[data-workspace-tile="shared"]')];
  assert.equal(copies.length, 2);
  assert.match(copies[0].getAttribute("aria-label"), /ana@example.test/);
  assert.match(copies[1].getAttribute("aria-label"), /bea@example.test/);
  copies[1].click();
  assert.ok(integrated.actions.includes("open/bea/shared"));
  copies[1].dispatchEvent(new app.w.KeyboardEvent("keydown", { key: "ContextMenu", bubbles: true }));
  assert.ok(await until(() => [...doc.querySelectorAll('[role="menuitem"]')].some((row) => row.textContent.includes("Cerrar sesión de Acme"))));
  assert.equal([...doc.querySelectorAll('[role="menuitem"]')].some((row) => row.textContent.includes("Canjear")), false);
  [...doc.querySelectorAll('[role="menuitem"]')].find((row) => row.textContent.includes("Cerrar sesión de Acme")).click();
  assert.ok(await until(() => integrated.actions.includes("close/bea")));
  integrated.dispose(); root.replaceChildren();
  const combined = mountOrganizationGroup(root, true); t.after(combined.dispose);
  const stackMenu = () => doc.querySelector('[data-org-stack="org"]').dispatchEvent(new app.w.KeyboardEvent("keydown", { key: "ContextMenu", bubbles: true }));
  stackMenu();
  assert.ok(await until(() => doc.querySelector('[data-account-menu-context="bea"]')));
  assert.equal(doc.querySelectorAll('[data-account-menu-context]').length, 2);
  assert.equal(doc.querySelector('[data-account-menu-context="ana"]').textContent.includes("Canjear código"), true);
  assert.equal(doc.querySelector('[data-account-menu-context="bea"]').textContent.includes("Canjear código"), false);
  assert.equal([...doc.querySelectorAll('[role="menuitem"]')].filter((row) => row.textContent === "Fijar en la barra").length, 1);
  assert.equal([...doc.querySelectorAll('[role="menuitem"]')].some((row) => row.textContent === "Administrar workspaces"), false);
  [...doc.querySelector('[data-account-menu-context="bea"]').querySelectorAll('button')].find((row) => row.textContent.includes("Cerrar sesión de Acme")).click();
  assert.ok(await until(() => combined.actions.includes("close/bea")));
  stackMenu();
  assert.ok(await until(() => doc.querySelector('[data-account-menu-context="ana"]')));
  [...doc.querySelector('[data-account-menu-context="ana"]').querySelectorAll('button')].find((row) => row.textContent.includes("Cerrar sesión de Acme")).click();
  assert.ok(await until(() => combined.actions.includes("close/ana")));
  combined.dispose(); root.replaceChildren();
  const single = mountOrganizationGroup(root, true, true); t.after(single.dispose);
  stackMenu();
  assert.ok(await until(() => doc.querySelector('[data-account-menu-context="ana"]')));
  assert.equal(doc.querySelectorAll('[data-account-menu-context]').length, 1);
  assert.equal([...doc.querySelectorAll('[role="menuitem"]')].filter((row) => row.textContent === "Fijar en la barra").length, 1);
  single.dispose(); root.replaceChildren();
  const web = mountWebOrganization(root); t.after(web.dispose);
  assert.ok(await until(() => root.querySelector('[data-rail-organization="org"]')));
  assert.equal(root.querySelector('[data-rail-organization="org"]').getAttribute("aria-label"), "Acme");
  const webTile = root.querySelector('[data-workspace-context="web-context"]');
  assert.match(webTile.getAttribute("aria-label"), /web@example.test/);
  webTile.dispatchEvent(new app.w.KeyboardEvent("keydown", { key: "F10", shiftKey: true, bubbles: true }));
  assert.ok(await until(() => [...doc.querySelectorAll('[role="menuitem"]')].some((row) => row.textContent.includes("Cerrar sesión de web@example.test"))));
  assert.equal([...doc.querySelectorAll('[role="menuitem"]')].some((row) => row.textContent.includes("Cerrar sesión de Acme")), false);
  assert.equal([...doc.querySelectorAll('[role="menuitem"]')].some((row) => row.textContent.includes("Canjear")), false);
  [...doc.querySelectorAll('[role="menuitem"]')].find((row) => row.textContent.includes("Cerrar sesión de web@example.test")).click();
  assert.ok(await until(() => web.actions.includes("sign-out")));
  assert.deepEqual(app.failures, []);

});
